/** Manual vouchers (journal, contra, receipt, payment entered directly). */
import { query, withTransaction, Queryable } from '../config/db';
import { AppError } from '../middleware/errorHandler';
import { postVoucher, removeVoucher, EntryInput } from './posting';
import { resolveFinancialYear, toDateString } from './financialYear';
import { docTypeForVoucherType, peekNextNumber } from './numberSeries';

export interface ManualVoucherInput {
    voucherTypeId: string;
    voucherNumber?: string | null;
    date: string;
    narration?: string | null;
    entries: EntryInput[];
}

/** Vouchers generated by invoices/payments must be changed through those documents. */
const assertNotLinked = async (db: Queryable, voucherId: string) => {
    const inv = await db.query('SELECT invoice_number FROM invoices WHERE voucher_id = $1', [voucherId]);
    if (inv.rows.length) {
        throw new AppError(`This voucher belongs to invoice ${inv.rows[0].invoice_number}. Edit the invoice instead.`, 400);
    }
    const pay = await db.query('SELECT 1 FROM payments WHERE voucher_id = $1', [voucherId]);
    if (pay.rows.length) throw new AppError('This voucher belongs to an invoice payment. Change it from the invoice.', 400);
    const rec = await db.query('SELECT 1 FROM receipts WHERE voucher_id = $1', [voucherId]);
    if (rec.rows.length) throw new AppError('This voucher belongs to a receipt/payment. Change it from Receipts & Payments.', 400);
};

export const createVoucher = (companyId: string, v: ManualVoucherInput) =>
    withTransaction((db) => postVoucher(db, { companyId, ...v }));

export const updateVoucher = (companyId: string, id: string, v: ManualVoucherInput) =>
    withTransaction(async (db) => {
        await assertNotLinked(db, id);
        await postVoucher(db, { companyId, ...v }, id);
    });

export const deleteVoucher = (companyId: string, id: string) =>
    withTransaction(async (db) => {
        await assertNotLinked(db, id);
        await removeVoucher(db, companyId, id);
    });

export const listVouchers = async (companyId: string, f: { fromDate?: string; toDate?: string; voucherTypeId?: string }) => {
    const params: any[] = [companyId];
    let sql = `SELECT v.*, vt.name AS voucher_type_name,
                      (SELECT i.id FROM invoices i WHERE i.voucher_id = v.id LIMIT 1) AS invoice_id
               FROM vouchers v LEFT JOIN voucher_types vt ON v.voucher_type_id = vt.id
               WHERE v.company_id = $1`;
    if (f.fromDate) {
        params.push(f.fromDate);
        sql += ` AND v.date >= $${params.length}`;
    }
    if (f.toDate) {
        params.push(f.toDate);
        sql += ` AND v.date <= $${params.length}`;
    }
    if (f.voucherTypeId) {
        params.push(f.voucherTypeId);
        sql += ` AND v.voucher_type_id = $${params.length}`;
    }
    sql += ' ORDER BY v.date DESC, v.created_at DESC';
    return (await query(sql, params)).rows;
};

export const listVoucherTypes = async (companyId: string) =>
    (await query('SELECT * FROM voucher_types WHERE company_id = $1 ORDER BY name', [companyId])).rows;

export const nextVoucherNumber = async (companyId: string, voucherTypeId: string, date: string) => {
    const vt = await query('SELECT name FROM voucher_types WHERE id = $1 AND company_id = $2', [voucherTypeId, companyId]);
    if (!vt.rows.length) throw new AppError('Invalid voucher type', 400);
    return withTransaction(async (db) => {
        const fy = await resolveFinancialYear(db, companyId, toDateString(date));
        return peekNextNumber(db, companyId, docTypeForVoucherType(vt.rows[0].name), fy);
    });
};

export const getVoucher = async (id: string) => {
    const v = await query(
        `SELECT v.*, vt.name AS voucher_type_name FROM vouchers v
         LEFT JOIN voucher_types vt ON v.voucher_type_id = vt.id WHERE v.id = $1`,
        [id]
    );
    const entries = await query(
        `SELECT ve.*, l.name AS ledger_name FROM voucher_entries ve
         LEFT JOIN ledgers l ON ve.ledger_id = l.id WHERE ve.voucher_id = $1
         ORDER BY CASE ve.type WHEN 'Dr' THEN 0 ELSE 1 END, ve.created_at`,
        [id]
    );
    return { voucher: v.rows[0], entries: entries.rows };
};
